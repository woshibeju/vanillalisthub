#include <string>
#include <vector>

void sort_small() {
    int values[4] = {9, 3, 7, 1};
    for (int i = 0; i < 4; ++i) {
        for (int j = i + 1; j < 4; ++j) {
            if (values[j] < values[i]) {
                int t = values[i];
                values[i] = values[j];
                values[j] = t;
            }
        }
    }
    (void)values[0];
}

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void geometric_sum() {
    int acc = 0;
    int term = 1;
    for (int i = 0; i < 8; ++i) { acc += term; term *= 2; }
    (void)acc;
}

void sum_pair() {
    int left = 3;
    int right = 9;
    int total = left + right;
    (void)total;
}

extern "C" int gentle_spruce();
extern "C" void calm_cove();
extern "C" void placid_ripple();
extern "C" void silver_haven();

int main() {
    sort_small();
    count_vowels();
    geometric_sum();
    sum_pair();
    calm_cove();
    placid_ripple();
    silver_haven();
    return gentle_spruce();
}
